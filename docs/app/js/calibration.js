// Slicer-free G-code generators for calibration prints. Every program uses relative
// extrusion (M83), absolute XYZ, layer markers (";LAYER:n") for camera snapshots and
// band markers (";KL_BAND i value") so results map back to the parameter tested.

export const DEFAULT_PROFILE = {
  name: 'My printer', bed_x: 220, bed_y: 220, max_z: 250, origin: 'corner',
  nozzle_mm: 0.4, filament_mm: 1.75, hotend_c: 205, bed_c: 60, max_hotend_c: 260, max_bed_c: 110,
  baud: 115200, travel_mm_s: 120, print_mm_s: 50, fan_percent: 100, retract_mm: 5, retract_mm_s: 40,
  start_gcode: '', end_gcode: '',
};

const r3 = v => Math.round(v * 1000) / 1000;
const r5 = v => Math.round(v * 100000) / 100000;

export class GcodeWriter {
  constructor(profile, {layerHeight = 0.2, lineWidth = null} = {}) {
    this.p = {...DEFAULT_PROFILE, ...profile};
    this.h = layerHeight;
    this.w = lineWidth || this.p.nozzle_mm * 1.125;
    this.lines = [];
    this.layer = -1;
    this.z = 0; this.x = 0; this.y = 0;
    this.retracted = false;
    const cx = this.p.origin === 'center' ? 0 : this.p.bed_x / 2;
    const cy = this.p.origin === 'center' ? 0 : this.p.bed_y / 2;
    this.center = {x: cx, y: cy};
  }
  get filamentArea() { return Math.PI * (this.p.filament_mm / 2) ** 2; }
  // Slic3r extrusion model: rectangle with semicircular ends.
  ePerMm(w = this.w, h = this.h) { return ((w - h) * h + Math.PI * (h / 2) ** 2) / this.filamentArea; }
  push(...l) { this.lines.push(...l); return this; }
  comment(t) { return this.push('; ' + t); }
  retract() { if (!this.retracted) { this.push(`G1 E-${this.p.retract_mm} F${this.p.retract_mm_s * 60}`); this.retracted = true; } }
  unretract() { if (this.retracted) { this.push(`G1 E${this.p.retract_mm} F${this.p.retract_mm_s * 60}`); this.retracted = false; } }
  travel(x, y, {retract = true} = {}) {
    const dist = Math.hypot(x - this.x, y - this.y);
    if (dist < 1e-6) return this;
    if (retract && dist > 2) this.retract();
    this.push(`G0 X${r3(x)} Y${r3(y)} F${this.p.travel_mm_s * 60}`);
    this.x = x; this.y = y;
    return this;
  }
  extrude(x, y, speed, w = this.w) {
    this.unretract();
    const d = Math.hypot(x - this.x, y - this.y);
    this.push(`G1 X${r3(x)} Y${r3(y)} E${r5(d * this.ePerMm(w))} F${Math.round(speed * 60)}`);
    this.x = x; this.y = y;
    return this;
  }
  newLayer(z) {
    this.layer++;
    this.z = z;
    this.push(`;LAYER:${this.layer}`, `G0 Z${r3(z)} F600`);
    if (this.layer === 1) this.push(`M106 S${Math.round(this.p.fan_percent * 2.55)}`);
    return this;
  }
  loop(points, speed) {
    this.travel(points[0][0], points[0][1]);
    for (let i = 1; i <= points.length; i++) { const [x, y] = points[i % points.length]; this.extrude(x, y, speed); }
    return this;
  }
  rect(cx, cy, sx, sy, speed) {
    const hx = sx / 2, hy = sy / 2;
    return this.loop([[cx - hx, cy - hy], [cx + hx, cy - hy], [cx + hx, cy + hy], [cx - hx, cy + hy]], speed);
  }
  start() {
    const p = this.p;
    this.push('; generated by KlipperLearn phone app', `; printer: ${p.name}`);
    if (p.start_gcode.trim()) this.push(...p.start_gcode.split(/\r?\n/));
    else this.push(`M140 S${p.bed_c}`, `M104 S${p.hotend_c}`, 'G28', `M190 S${p.bed_c}`, `M109 S${p.hotend_c}`);
    this.push('G90', 'M83', 'G92 E0', 'M107');
    // Prime line along the front-left edge, inside the bed.
    const x0 = this.p.origin === 'center' ? -p.bed_x / 2 + 5 : 5;
    const y0 = this.p.origin === 'center' ? -p.bed_y / 2 + 10 : 10;
    const len = Math.min(100, p.bed_y - 30);
    this.push(`G0 Z0.3 F600`, `G0 X${x0} Y${y0} F${p.travel_mm_s * 60}`);
    this.x = x0; this.y = y0;
    this.extrude(x0, y0 + len, 25, this.w * 1.5).extrude(x0 + 0.5, y0 + len, 25).extrude(x0 + 0.5, y0, 25, this.w * 1.5);
    return this;
  }
  end() {
    const p = this.p;
    this.retract();
    this.push(`G0 Z${r3(Math.min(p.max_z, this.z + 10))} F600`, 'M104 S0', 'M140 S0', 'M107');
    if (p.end_gcode.trim()) this.push(...p.end_gcode.split(/\r?\n/));
    else this.push('M84');
    return this;
  }
}

function sweep(start, step, count) { return Array.from({length: count}, (_, i) => r3(start + step * i)); }

// Hollow square tube whose parameter changes every `bandMm`. Used for temperature,
// acceleration (ringing), speed and pressure-advance towers.
function bandTower(profile, {title, bandMm = 5, values, size = 30, walls = 2, speed, bandCommand, speedFor = null}) {
  const g = new GcodeWriter(profile).start();
  const layersPerBand = Math.round(bandMm / g.h);
  const totalLayers = layersPerBand * values.length;
  const {x: cx, y: cy} = g.center;
  g.comment(`${title}: ${values.length} bands of ${bandMm} mm`);
  for (let L = 0; L < totalLayers; L++) {
    g.newLayer(r3(0.2 + L * g.h));
    const band = Math.floor(L / layersPerBand);
    if (L % layersPerBand === 0) g.push(`;KL_BAND ${band} ${values[band]}`, ...[].concat(bandCommand(values[band])));
    const v = L === 0 ? 20 : (speedFor ? speedFor(values[band]) : speed);
    if (L === 0) for (let b = 3; b >= 1; b--) g.rect(cx, cy, size + 2 * b * g.w, size + 2 * b * g.w, v); // brim
    for (let wIdx = 0; wIdx < walls; wIdx++) g.rect(cx, cy, size - 2 * wIdx * g.w, size - 2 * wIdx * g.w, v);
  }
  return g.end();
}

