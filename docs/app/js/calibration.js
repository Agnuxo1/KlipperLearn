// EXPERIMENTAL: shake one axis at known frequencies (no heating, no extrusion) while the
// phone, firmly attached to the bed or toolhead, records acceleration. Bang-bang moves of
// amplitude A with acceleration a have a period of 4*sqrt(2A/a), so A = a / (32 f^2).
// Each frequency is framed by M400 so the app knows when that segment ran.
export function resonanceSweep(profile, {axis = 'X', fromHz = 20, toHz = 80, stepHz = 5, accel = 2000, secondsPer = 1.5} = {}) {
  const p = {...DEFAULT_PROFILE, ...profile};
  const c = axis === 'X' ? (p.origin === 'center' ? 0 : p.bed_x / 2) : (p.origin === 'center' ? 0 : p.bed_y / 2);
  const lines = ['; KlipperLearn resonance sweep (experimental, no extrusion)', 'G28', 'G90',
    `G0 Z${Math.min(20, p.max_z / 2)} F600`, `G0 X${p.origin === 'center' ? 0 : p.bed_x / 2} Y${p.origin === 'center' ? 0 : p.bed_y / 2} F6000`,
    `M204 P${accel} T${accel}`, 'M400'];
  const freqs = [];
  for (let f = fromHz; f <= toHz + 1e-9; f += stepHz) {
    const amp = Math.max(0.02, accel / (32 * f * f));
    const vPeak = Math.sqrt(accel * 2 * amp);                   // mm/s at mid-stroke
    const feed = Math.round(Math.min(vPeak * 1.5, 300) * 60);
    lines.push(`;KL_FREQ ${f}`);
    for (let i = 0; i < Math.round(f * secondsPer); i++) {
      lines.push(`G1 ${axis}${r3(c + amp)} F${feed}`, `G1 ${axis}${r3(c - amp)} F${feed}`);
    }
    lines.push(`G1 ${axis}${r3(c)} F${feed}`, 'M400', `;KL_FREQ_END ${f}`);
    freqs.push(f);
  }
  lines.push('M84');
  return {freqs, gcode: lines};
}

// Klipper's documented ringing method: N oscillations over D mm printed at v mm/s.
export function ringingFrequency(speedMmS, ripples, distanceMm) {
  if (!(speedMmS > 0 && ripples > 0 && distanceMm > 0)) return null;
  return speedMmS * ripples / distanceMm;
}

// Rough print-time estimate for a generated program (ignores acceleration).
export function estimateSeconds(lines) {
  let x = 0, y = 0, z = 0, t = 0, f = 3000;
  for (const l of lines) {
    const m = l.match(/^G[01]\s(.*)/);
    if (!m) continue;
    const get = k => { const r = m[1].match(new RegExp(`${k}(-?[\\d.]+)`)); return r ? parseFloat(r[1]) : null; };
    const nf = get('F'); if (nf) f = nf;
    const nx = get('X') ?? x, ny = get('Y') ?? y, nz = get('Z') ?? z, e = get('E') ?? 0;
    const d = Math.max(Math.hypot(nx - x, ny - y, nz - z), Math.abs(e) * (nx === x && ny === y ? 1 : 0));
    t += d / (f / 60);
    x = nx; y = ny; z = nz;
  }
  return t;
}
